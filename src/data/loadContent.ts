/**
 * ⚠ КАРКАС — docs/CORE.md, раздел 3. Единственный вход в полные тексты базы.
 *
 * data/content.ts — описания, параллели, статьи, источники, трактовки и
 * объяснения связей — самый тяжёлый чанк сайта. Шкала живёт на витрине
 * (заголовок, дата, одна фраза), а за текстами идёт только тогда, когда
 * читатель «проваливается» внутрь: выбирает карточку, открывает окно,
 * ищет по тексту или выгружает конспект. Все они берут модуль отсюда,
 * поэтому он скачивается один раз.
 */
let pending: Promise<typeof import('./content')> | undefined;

export function loadContent(): Promise<typeof import('./content')> {
  pending ??= import('./content');
  return pending;
}
