/**
 * Доменная модель хронологии.
 *
 * Модель намеренно описана «с запасом»: сейчас шкала строится по годам,
 * но каждый объект уже может нести месяц и день, диапазон лет и вес важности.
 * Благодаря этому переход к делению «год → месяц → день» не потребует
 * миграции данных — достаточно поменять уровень группировки (см. lib/timeline.ts).
 */

/**
 * Stable catalog key rather than a closed union. Countries and historical
 * polities are data, so adding a line must not require changing the type system.
 */
export type CountryId = string;

export type TimelineItemKind = 'event' | 'person';

/**
 * Вес объекта на шкале.
 * 3 — опорная веха эпохи, 2 — заметное событие, 1 — деталь/контекст.
 */
export type Importance = 1 | 2 | 3;

/** Уровень группировки шкалы. Сейчас в UI используется 'year', остальные — задел на будущее. */
export type Granularity = 'year' | 'month' | 'day';

export type EraId =
  | 'deep-prehistory'
  | 'prehistory'
  | 'ancient-civilizations'
  | 'antiquity'
  | 'early-middle-ages'
  | 'high-middle-ages'
  | 'early-modern'
  | 'age-of-revolutions'
  | 'industrial'
  | 'world-wars'
  | 'cold-war'
  | 'contemporary';

export type Era = {
  id: EraId;
  label: string;
  /** Первый год эпохи включительно. */
  from: number;
  /** Последний год эпохи включительно. */
  to: number;
  note: string;
};

/** Тип источника — влияет на то, насколько он весом при проверке факта. */
export type SourceKind =
  /** Энциклопедия: отправная точка, но не единственное подтверждение. */
  | 'encyclopedia'
  /** Академическая публикация, монография, рецензируемая статья. */
  | 'academic'
  /** Архив, публикация документа, официальный государственный источник. */
  | 'archive'
  /** Музей, библиотека, научно-популярный ресурс профильного учреждения. */
  | 'institution'
  /** Печатный справочник: источник импорта, но не независимая верификация. */
  | 'reference';

export type SourceLink = {
  label: string;
  url?: string;
  kind?: SourceKind;
};

/**
 * Одна из устоявшихся трактовок факта.
 *
 * Нужна там, где историография разных стран или школ расходится в оценке,
 * но сам факт при этом не оспаривается. Каждая трактовка обязана быть
 * атрибутирована: кто именно так считает.
 */
export type Viewpoint = {
  id: string;
  /** Чья трактовка: страна, школа, традиция. */
  label: string;
  /** Оттенок для визуального различения, 1–4. */
  tone: 1 | 2 | 3 | 4;
  /** Изложение трактовки в Markdown. */
  text: string;
  /** Историографические работы, в которых эта трактовка действительно представлена. */
  sources: SourceLink[];
};

export type TimelineItem = {
  id: string;
  country: CountryId;
  /** Год размещения на шкале. Может быть годом ключевого действия, а не рождения. */
  year: number;
  /** Печатная формулировка неточной или составной даты: диапазон, век, «около». */
  dateLabel?: string;
  /** 1–12. Задел на помесячную детализацию. */
  month?: number;
  /** 1–31. Задел на подневную детализацию. */
  day?: number;
  /** Год окончания процесса, если объект описывает не точку, а отрезок. */
  endYear?: number;
  kind: TimelineItemKind;
  title: string;
  /** Одно предложение: что произошло. */
  summary: string;
  /** 2–4 предложения: что произошло, почему важно, как связано с соседями. */
  detail: string;
  /** Годы жизни — только для персоналий. */
  life?: string;
  tags: string[];
  importance?: Importance;
  /** Короткая реплика о синхронности: что в это же время происходило рядом. */
  parallel?: string;
  /**
   * Полный текст статьи в Markdown для модального окна.
   * Если поля нет, документ собирается из остальных полей — см. lib/markdown.ts.
   */
  body?: string;
  /**
   * Источники, по которым факт проверен. Требование к базе — минимум два
   * независимых источника, из которых хотя бы один не энциклопедия.
   */
  sources?: SourceLink[];
  /**
   * Устоявшиеся расхождения в трактовке. Сам факт при этом не оспаривается —
   * расходятся оценки и акценты. Если трактовок больше одной, карточка
   * помечается значком, а в окне они показываются разными оттенками.
   */
  viewpoints?: Viewpoint[];
  /**
   * Дата известна приблизительно: год условный, спорный или реконструированный.
   * Показывается как «около» и не участвует в подневной детализации.
   */
  approximate?: boolean;
  /** Объект добавлен пользователем через конструктор персоналий. */
  custom?: boolean;
  /** Объект пришёл из наложенного слоя — см. data/layers.ts. */
  layerId?: string;
  /** Редакционный статус факта; старые записи определяются по комплекту источников. */
  verification?: 'verified' | 'reference' | 'draft';
  /** Страница печатного справочника, из которой импортирована запись. */
  referencePage?: number;
};

export type CountryKind = 'modern' | 'historical' | 'global';

export type CountryRegion =
  | 'global'
  | 'europe'
  | 'asia'
  | 'africa'
  | 'middle-east'
  | 'north-america'
  | 'latin-america'
  | 'oceania'
  | 'historical';

export type Country = {
  id: CountryId;
  label: string;
  /** Короткое обозначение для шапки таблицы. */
  short: string;
  /** Пояснение исторической линии: чем эта колонка является для ранних веков. */
  note: string;
  /** Базовый цвет линии, точек и акцентов. Хранится как HSL-компоненты. */
  color: string;
  /** Более тёмный вариант цвета для светлой «пергаментной» темы. */
  colorInk: string;
  /** Современная страна, историческое государство/цивилизация или общая линия мира. */
  kind?: CountryKind;
  /** Географическая группа для масштабируемого каталога выбора. */
  region?: CountryRegion;
  /** Дополнительные названия, по которым линия находится в поиске. */
  aliases?: string[];
};

/**
 * Набор стран — сохранённая подборка линий.
 *
 * Встроенные наборы приходят из data/countrySets.ts, свои читатель собирает сам;
 * различие только в `builtin`, всё остальное устроено одинаково.
 */
export type CountrySet = {
  id: string;
  label: string;
  /** Короткое пояснение: чем этот набор полезен. Своим наборам не нужно. */
  note?: string;
  countries: CountryId[];
  builtin?: boolean;
};

/** Слой фильтрации по типу объекта. */
export type KindFilter = 'all' | 'events' | 'people';

/**
 * Выбранный отрезок времени — либо содержательная эпоха, либо механический
 * интервал в 300 лет. Выбран может быть только один: см. data/periods.ts.
 */
export type Period =
  | { type: 'era'; id: EraId }
  | { type: 'interval'; from: number; to: number };

/** Тема оформления. */
export type ThemeName = 'parchment' | 'atlas';

/**
 * Дорожка внутри колонки — общая абстракция для страны и для наложенного слоя.
 *
 * Благодаря ей колонка не знает, что именно в ней лежит: она рисует по одной
 * вертикальной шкале на дорожку, а карточка садится на шкалу своей дорожки.
 * Так «две страны в одной колонке» и «слой поверх страны» — один механизм.
 */
export type Track = {
  id: string;
  label: string;
  short: string;
  /** Цвет в виде HSL-компонентов. */
  color: string;
  colorInk: string;
  kind: 'country' | 'layer';
  countryId?: CountryId;
  layerId?: string;
};

/**
 * Колонка таблицы. Держит одну или несколько дорожек.
 *
 * Дорожек больше одной в двух случаях: пользователь объединил две страны
 * либо положил на страну слой. Внутри колонки они различаются цветом точки
 * и бейджем на карточке.
 */
export type TimelineColumn = {
  /** Идентификатор колонки: 'russia', 'russia+belarus', 'layer:einstein'. */
  id: string;
  tracks: Track[];
  /** Подпись в шапке: «Россия · Беларусь». */
  label: string;
  /** Короткое обозначение: «RU · BY». */
  short: string;
  /** Колонка держит больше одной дорожки. */
  shared: boolean;
  /** Колонка целиком отдана слою и не привязана к стране. */
  layerOnly?: boolean;
};

/**
 * Наложенный слой — набор событий одного сюжета: жизнь человека,
 * череда эпидемий, история технологии.
 *
 * Слои по умолчанию выключены: на поверхности шкалы только значимые события.
 * Включённый слой кладётся на колонку выбранной страны или получает свою —
 * и его можно перетащить мышью из страны в страну.
 */
export type Layer = {
  id: string;
  title: string;
  /** Короткая подпись: годы жизни, область, охват. */
  subtitle?: string;
  /** Зачем этот слой и что он показывает рядом с историей стран. */
  note: string;
  short: string;
  color: string;
  colorInk: string;
  /**
   * Раздел выпадающего меню: биографии сортируются по алфавиту,
   * сюжетные слои — по времени начала.
   */
  category: 'person' | 'event';
  /** Куда положить при включении: на страну или в собственную колонку. */
  defaultPlacement: CountryId | typeof OWN_COLUMN;
  items: LayerItem[];
};

/** Куда положен слой: на колонку страны или в собственную. */
export const OWN_COLUMN = 'own' as const;
export type LayerPlacement = CountryId | typeof OWN_COLUMN;

/**
 * Объект слоя. Отличается от обычного тем, что не привязан к стране:
 * страну ему даёт размещение слоя, и она меняется при перетаскивании.
 */
export type LayerItem = Omit<TimelineItem, 'country' | 'custom'>;

/** Группа объектов одного «шага» шкалы (сейчас — одного года). */
export type TimelineGroup = {
  /** Стабильный ключ группы: 'y:1789' | 'm:1789:7' | 'd:1789:7:14'. */
  key: string;
  year: number;
  month?: number;
  day?: number;
  /** Подпись группы для колонки дат. */
  label: string;
  /** Уточнение под подписью: год при детализации по месяцам и дням. */
  sublabel?: string;
  era: Era;
  /** Первая группа эпохи — по ней рисуется разделитель эпохи. */
  startsEra: boolean;
  items: TimelineItem[];
  /** Объекты, разложенные по колонкам таблицы (ключ — TimelineColumn.id). */
  byColumn: Record<string, TimelineItem[]>;
  /** Максимальная важность внутри группы — влияет на вес подписи года. */
  weight: Importance;
};

/**
 * Связь между двумя объектами хронологии — обычно из разных стран.
 * На шкале рисуется нитью-графом между узлами карточек.
 */
export type Relation = {
  id: string;
  /** Первый объект связи; направление значимо только для `influence`. */
  from: string;
  /** Второй объект связи; для симметричных видов порядок служебный. */
  to: string;
  /** Короткая подпись связи для подсказки и заголовка окна. */
  label: string;
  /** Подробное объяснение связи в Markdown. */
  detail: string;
  /** Характер связи — определяет направленность, подписи ролей, цвет и штрих нити. */
  kind: 'influence' | 'conflict' | 'exchange' | 'comparison' | 'context';
  /**
   * Источники, подтверждающие именно заявленный характер связи.
   * Источники объектов по краям не заменяют источники самой связи.
   */
  sources?: SourceLink[];
  /**
   * `verified` разрешён только при двух независимых источниках, среди которых
   * есть хотя бы один неэнциклопедический. Старые записи без статуса считаются
   * редакционными черновиками и рисуются пунктиром.
   */
  verification?: 'verified' | 'draft';
};

/** Проверенная связь, которую пользователь заполняет в конструкторе. */
export type RelationDraftInput = Pick<Relation, 'to' | 'kind' | 'label' | 'detail' | 'sources'>;

/** Один осмысленный шаг кураторского маршрута по шкале. */
export type StoryStep = {
  itemId: string;
  title: string;
  note: string;
};

/** Короткий учебный маршрут, связывающий несколько стран и эпох. */
export type Story = {
  id: string;
  title: string;
  summary: string;
  minutes: number;
  steps: StoryStep[];
};

export type Suggestion = {
  id: string;
  /** Готовый объект, который добавится в хронологию. */
  item: Omit<TimelineItem, 'id' | 'custom'>;
  /** Почему этого деятеля стоит поставить именно в этот год. */
  why: string;
};
